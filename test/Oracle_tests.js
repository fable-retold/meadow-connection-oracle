/**
* Unit tests for the Meadow Oracle connection package (no-DB surfaces).
*
* These exercise the DDL string generation and index derivation, which are
* pure functions of the schema and require no Oracle connection.  The live
* connection / introspection / CRUD behaviors are covered by the Docker suite.
*
* @license MIT
* @author Steven Velozo <steven@velozo.com>
*/

const Chai = require('chai');
const Expect = Chai.expect;

const libFable = require('fable');
const libMeadowSchemaOracle = require('../source/Meadow-Schema-Oracle.js');

const _FableTestTableSchema = (
{
	TableName: 'FableTest',
	Columns:
	[
		{ Column: 'IDFableTest',   DataType: 'ID' },
		{ Column: 'GUIDFableTest', DataType: 'GUID' },
		{ Column: 'Title',         DataType: 'String', Size: '256' },
		{ Column: 'Description',   DataType: 'Text' },
		{ Column: 'IDAuthor',      DataType: 'ForeignKey' }
	]
});

function makeSchemaProvider(pOracleSettings)
{
	let tmpFable = new libFable({ Product: 'MeadowOracleSchemaTests', Oracle: pOracleSettings || {} });
	tmpFable.serviceManager.addServiceType('MeadowSchemaOracle', libMeadowSchemaOracle);
	return tmpFable.serviceManager.instantiateServiceProvider('MeadowSchemaOracle');
}

suite('Meadow-Connection-Oracle (no-DB)',
	() =>
	{
		suite('CREATE TABLE generation',
			() =>
			{
				test('12c identity column + Oracle type map (unquoted)',
					() =>
					{
						let tmpSchema = makeSchemaProvider();
						let tmpStatement = tmpSchema.generateCreateTableStatement(_FableTestTableSchema);
						Expect(tmpStatement).to.equal(
							'CREATE TABLE FableTest\n' +
							'    (\n' +
							'        IDFableTest NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n' +
							"        GUIDFableTest VARCHAR2(255) DEFAULT '00000000-0000-0000-0000-000000000000' NOT NULL,\n" +
							"        Title VARCHAR2(256) DEFAULT ' ',\n" +
							'        Description CLOB,\n' +
							'        IDAuthor NUMBER DEFAULT 0 NOT NULL\n' +
							'    )');
					});

				test('quoteIdentifiers wraps identifiers in double quotes',
					() =>
					{
						let tmpSchema = makeSchemaProvider({ QuoteIdentifiers: true });
						let tmpStatement = tmpSchema.generateCreateTableStatement(_FableTestTableSchema);
						Expect(tmpStatement).to.include('CREATE TABLE "FableTest"');
						Expect(tmpStatement).to.include('"IDFableTest" NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
						Expect(tmpStatement).to.include('"Title" VARCHAR2(256)');
					});

				test('legacy identity uses a plain NUMBER PK plus sequence + trigger statements',
					() =>
					{
						let tmpSchema = makeSchemaProvider({ LegacyIdentity: true });
						let tmpStatements = tmpSchema.generateCreateTableStatements(_FableTestTableSchema);
						Expect(tmpStatements.length).to.equal(3);
						Expect(tmpStatements[0]).to.include('IDFableTest NUMBER PRIMARY KEY');
						Expect(tmpStatements[0]).to.not.include('IDENTITY');
						Expect(tmpStatements[1]).to.equal('CREATE SEQUENCE SEQ_FableTest START WITH 1 INCREMENT BY 1 NOCACHE');
						Expect(tmpStatements[2]).to.equal(
							'CREATE OR REPLACE TRIGGER TRG_FableTest\n' +
							'    BEFORE INSERT ON FableTest\n' +
							'    FOR EACH ROW\n' +
							'    WHEN (NEW.IDFableTest IS NULL)\n' +
							'BEGIN\n' +
							'    SELECT SEQ_FableTest.NEXTVAL INTO :NEW.IDFableTest FROM DUAL;\n' +
							'END;');
					});

				test('12c path produces a single CREATE TABLE statement',
					() =>
					{
						let tmpSchema = makeSchemaProvider();
						let tmpStatements = tmpSchema.generateCreateTableStatements(_FableTestTableSchema);
						Expect(tmpStatements.length).to.equal(1);
					});
			});

		suite('DROP TABLE generation',
			() =>
			{
				test('wraps the drop in a PL/SQL block that swallows ORA-00942',
					() =>
					{
						let tmpSchema = makeSchemaProvider();
						let tmpStatement = tmpSchema.generateDropTableStatement('FableTest');
						Expect(tmpStatement).to.equal(
							'BEGIN\n' +
							"    EXECUTE IMMEDIATE 'DROP TABLE FableTest CASCADE CONSTRAINTS';\n" +
							'EXCEPTION\n' +
							'    WHEN OTHERS THEN\n' +
							'        IF SQLCODE != -942 THEN RAISE; END IF;\n' +
							'END;');
					});
			});

		suite('Index derivation',
			() =>
			{
				test('auto-derives a unique index for GUID and a regular index for ForeignKey',
					() =>
					{
						let tmpSchema = makeSchemaProvider();
						let tmpIndices = tmpSchema.getIndexDefinitionsFromSchema(_FableTestTableSchema);
						Expect(tmpIndices.length).to.equal(2);
						Expect(tmpIndices[0].Name).to.equal('AK_M_GUIDFableTest');
						Expect(tmpIndices[0].Unique).to.equal(true);
						Expect(tmpIndices[1].Name).to.equal('IX_M_IDAuthor');
						Expect(tmpIndices[1].Unique).to.equal(false);
					});

				test('generates CREATE INDEX statements with USER_INDEXES existence checks',
					() =>
					{
						let tmpSchema = makeSchemaProvider();
						let tmpStatements = tmpSchema.generateCreateIndexStatements(_FableTestTableSchema);
						Expect(tmpStatements.length).to.equal(2);
						Expect(tmpStatements[0].Statement).to.equal('CREATE UNIQUE INDEX AK_M_GUIDFableTest ON FableTest (GUIDFableTest)');
						Expect(tmpStatements[0].CheckStatement).to.equal("SELECT COUNT(*) AS INDEXEXISTS FROM USER_INDEXES WHERE INDEX_NAME = 'AK_M_GUIDFABLETEST' AND TABLE_NAME = 'FABLETEST'");
						Expect(tmpStatements[1].Statement).to.equal('CREATE INDEX IX_M_IDAuthor ON FableTest (IDAuthor)');
					});

				test('includes explicit composite indices from the schema',
					() =>
					{
						let tmpSchema = makeSchemaProvider();
						let tmpTableSchema = {
							TableName: 'FableTest',
							Columns: [ { Column: 'IDFableTest', DataType: 'ID' }, { Column: 'A', DataType: 'Numeric' }, { Column: 'B', DataType: 'Numeric' } ],
							Indices: [ { Name: 'IX_AB', Columns: ['A', 'B'], Unique: false } ]
						};
						let tmpStatements = tmpSchema.generateCreateIndexStatements(tmpTableSchema);
						Expect(tmpStatements.length).to.equal(1);
						Expect(tmpStatements[0].Statement).to.equal('CREATE INDEX IX_AB ON FableTest (A, B)');
					});
			});

		suite('Connection-form UI data (pict-section-connection-form contract)',
			() =>
			{
				const libFormSchema = require('../source/Meadow-Connection-Oracle-FormSchema.js');
				const _SupportedTypes = ['String', 'Number', 'Password', 'Boolean', 'Path', 'Select'];

				test('exposes Provider, DisplayName, and a non-empty Fields array',
					() =>
					{
						Expect(libFormSchema.Provider).to.equal('Oracle');
						Expect(libFormSchema.DisplayName).to.be.a('string');
						Expect(libFormSchema.Fields).to.be.an('array');
						Expect(libFormSchema.Fields.length).to.be.greaterThan(0);
					});

				test('every field uses a Type the section knows how to render',
					() =>
					{
						libFormSchema.Fields.forEach((pField) =>
						{
							Expect(pField.Name, 'field missing Name').to.be.a('string');
							Expect(pField.Label, `field ${pField.Name} missing Label`).to.be.a('string');
							Expect(_SupportedTypes, `field ${pField.Name} has unsupported Type ${pField.Type}`).to.include(pField.Type);
						});
					});

				test('connectionType is a Select with ServiceName and SID options',
					() =>
					{
						let tmpField = libFormSchema.Fields.find((pF) => pF.Name === 'connectionType');
						Expect(tmpField).to.be.an('object');
						Expect(tmpField.Type).to.equal('Select');
						Expect(tmpField.Options).to.be.an('array');
						let tmpValues = tmpField.Options.map((pO) => pO.Value);
						Expect(tmpValues).to.include('ServiceName');
						Expect(tmpValues).to.include('SID');
						tmpField.Options.forEach((pO) =>
						{
							Expect(pO.Value).to.be.a('string');
							Expect(pO.Label).to.be.a('string');
						});
					});

				test('legacy flags omit-if-falsy so an unchecked box auto-detects',
					() =>
					{
						['LegacyPagination', 'LegacyIdentity'].forEach((pName) =>
						{
							let tmpField = libFormSchema.Fields.find((pF) => pF.Name === pName);
							Expect(tmpField, `${pName} missing`).to.be.an('object');
							Expect(tmpField.Type).to.equal('Boolean');
							Expect(tmpField.OmitIfFalsy, `${pName} should OmitIfFalsy`).to.equal(true);
						});
					});

				test('exposes the connection essentials (server, port, user, password, serviceName)',
					() =>
					{
						let tmpNames = libFormSchema.Fields.map((pF) => pF.Name);
						['server', 'port', 'user', 'password', 'serviceName'].forEach((pName) =>
						{
							Expect(tmpNames, `missing field ${pName}`).to.include(pName);
						});
					});
			});
	});
